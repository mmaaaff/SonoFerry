#!/usr/bin/env python3
"""Embed audited offline configuration for both SPM and the direct swiftc build."""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
profiles = json.loads((root / 'Configuration/OppoProfiles.json').read_text())
assert len(profiles) == len({p['id'] for p in profiles}) == 58
payload = json.dumps(profiles, ensure_ascii=False, separators=(',', ':'))
generated = ('// Generated by scripts/generate-headphone-catalog.py; Melody 17.6.3.\n// Evidence: docs/research/oppo-family-implementation-20261014/\nenum HeadphoneCatalogData {\n    static let json = #"""\n' + payload + '\n"""#\n}\n')

output = root / 'Sources/Core/HeadphoneCatalogData.swift'
if '--check' in sys.argv:
    if output.read_text() != generated: raise SystemExit('Embedded headphone catalogue is stale; run scripts/generate-headphone-catalog.py')
else:
    output.write_text(generated)
